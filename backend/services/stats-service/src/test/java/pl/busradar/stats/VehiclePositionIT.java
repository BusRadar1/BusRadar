package pl.busradar.stats;

import static org.assertj.core.api.Assertions.assertThat;

import java.time.Duration;
import java.time.Instant;
import java.util.Map;
import org.awaitility.Awaitility;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.kafka.core.KafkaTemplate;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;
import org.testcontainers.kafka.ConfluentKafkaContainer;
import org.testcontainers.postgresql.PostgreSQLContainer;
import org.testcontainers.utility.DockerImageName;
import pl.busradar.events.VehiclePositionEvent;

@SpringBootTest
// @Testcontainers tells JUnit 5 to manage lifecycle of @Container fields (start/stop)
@Testcontainers
public class VehiclePositionIT {

    @Container
    @SuppressWarnings("resource") // closed by @Testcontainers after the tests
    static PostgreSQLContainer postgres = new PostgreSQLContainer("postgres:17")
            .withDatabaseName("busradar")
            .withUsername("busradar")
            .withPassword("postgres")
            .withInitScript("init-stats-schema.sql");

    @Container
    static ConfluentKafkaContainer kafka =
            new ConfluentKafkaContainer(DockerImageName.parse("confluentinc/cp-kafka:7.6.1"));

    // Inject random ports generated by Docker into Spring Boot properties
    @DynamicPropertySource
    static void registerDynamicProperties(DynamicPropertyRegistry registry) {
        // Wire Database
        registry.add("spring.datasource.url", postgres::getJdbcUrl);
        registry.add("spring.datasource.username", postgres::getUsername);
        registry.add("spring.datasource.password", postgres::getPassword);

        // Wire Kafka (matches KAFKA_BOOTSTRAP_SERVERS env var)
        registry.add("spring.kafka.bootstrap-servers", kafka::getBootstrapServers);
        // The test publishes events as JSON (Jackson 3), like ingest-service will
        registry.add(
                "spring.kafka.producer.value-serializer",
                () -> "org.springframework.kafka.support.serializer.JacksonJsonSerializer");
    }

    // Inject the tools needed for the test
    @Autowired
    private KafkaTemplate<String, Object> kafkaTemplate;

    @Autowired
    private JdbcTemplate jdbcTemplate;

    @Test
    void shouldConsumeEventAndStoreInDatabaseWithoutDuplicates() {
        // ARRANGE

        // Valid VehiclePositionEvent record - Vehicle 468 from
        // tmp/ztm-test/2026-11-09-07.jsonl.gz
        VehiclePositionEvent event = new VehiclePositionEvent(
                468L,
                "2737",
                "911-01",
                "911",
                911,
                101,
                Instant.parse("2026-11-09T07:24:00Z"),
                "Górki Zachodnie",
                54.3578987121582,
                18.686790466308594,
                15,
                45,
                24,
                3,
                Instant.parse("2026-11-09T07:26:30Z"),
                Instant.parse("2026-11-09T07:26:45Z"));

        // Publish first event
        kafkaTemplate.send("vehicle-positions", String.valueOf(event.vehicleId()), event);

        // ASSERT Check Database
        // Use Awaitility to poll the database until SELECT count(*) == 1

        Awaitility.await().atMost(Duration.ofSeconds(5)).untilAsserted(() -> {
            Integer count = jdbcTemplate.queryForObject(
                    "SELECT count(*) FROM stats.vehicle_positions_raw WHERE vehicle_id = 468", Integer.class);
            assertThat(count).isEqualTo(1);
        });

        // ACT Publish Duplicate
        // Send the EXACT same event to Kafka again
        kafkaTemplate.send("vehicle-positions", String.valueOf(event.vehicleId()), event);

        // ASSERT Verify ON CONFLICT DO NOTHING
        // and assert that the database count is STILL exactly 1.

        Awaitility.await()
                .during(Duration.ofSeconds(2))
                .atMost(Duration.ofSeconds(5))
                .untilAsserted(() -> {
                    Integer count = jdbcTemplate.queryForObject(
                            "SELECT count(*) FROM stats.vehicle_positions_raw WHERE vehicle_id = 468", Integer.class);
                    assertThat(count).isEqualTo(1);
                });
    }

    @Test
    void shouldStoreNullsWhenVehicleHasNoTrip() {
        // ARRANGE

        // Vehicle 145591 from the API sample: no trip assigned, so tripId and
        // scheduledTripStartTime are null and headsign is empty.
        VehiclePositionEvent event = new VehiclePositionEvent(
                145591L,
                "2658",
                "227-04",
                "227",
                227,
                null,
                null,
                "",
                54.41535186767578,
                18.586809158325195,
                50,
                180,
                0,
                3,
                Instant.parse("2026-11-04T21:45:20Z"),
                Instant.parse("2026-11-04T21:45:25Z"));

        // ACT
        kafkaTemplate.send("vehicle-positions", String.valueOf(event.vehicleId()), event);

        // ASSERT the row arrives
        Awaitility.await().atMost(Duration.ofSeconds(10)).untilAsserted(() -> {
            Integer count = jdbcTemplate.queryForObject(
                    "SELECT count(*) FROM stats.vehicle_positions_raw WHERE vehicle_id = 145591", Integer.class);
            assertThat(count).isEqualTo(1);
        });

        // ASSERT the nullable columns really are NULL, not 0 or epoch
        Map<String, Object> row = jdbcTemplate.queryForMap(
                "SELECT trip_id, scheduled_trip_start, headsign FROM stats.vehicle_positions_raw WHERE vehicle_id = 145591");
        assertThat(row.get("trip_id")).isNull();
        assertThat(row.get("scheduled_trip_start")).isNull();
        assertThat(row.get("headsign")).isEqualTo("");
    }
}
